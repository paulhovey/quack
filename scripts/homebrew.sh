#!/usr/bin/env bash
# Write Homebrew formulas for a release, from its SHA256SUMS:
#
#   scripts/homebrew.sh <version> <SHA256SUMS> [out-dir]
#
# Writes quack.rb (binary and defaults bundle) and quack-plucked.rb (the same without the
# hosted model services) for a tap repository (Formula/ in
# github.com/<owner>/homebrew-quack). They point at the release's archives for macOS and
# Linux, on Intel and ARM.
set -euo pipefail

version=${1:?usage: homebrew.sh <version> <SHA256SUMS> [out-dir]}
version=${version#v}
sums=${2:?usage: homebrew.sh <version> <SHA256SUMS> [out-dir]}
out=${3:-dist}
repo=https://github.com/paulhovey/quack
mkdir -p "$out"

sha() {
  local sum
  sum=$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  [ -n "$sum" ] || { echo "homebrew.sh: $1 is not in $sums" >&2; exit 1; }
  echo "$sum"
}

formula() {
  local flavour=$1 class=$2 conflicts=$3 desc=$4 share=$5
  local url=$repo/releases/download/v$version
  cat <<EOF
# Generated by scripts/homebrew.sh for quack $version.
class $class < Formula
  desc "$desc"
  homepage "$repo"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$url/$flavour-aarch64-apple-darwin.tar.gz"
      sha256 "$(sha "$flavour-aarch64-apple-darwin.tar.gz")"
    end
    on_intel do
      url "$url/$flavour-x86_64-apple-darwin.tar.gz"
      sha256 "$(sha "$flavour-x86_64-apple-darwin.tar.gz")"
    end
  end

  on_linux do
    on_arm do
      url "$url/$flavour-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$(sha "$flavour-aarch64-unknown-linux-musl.tar.gz")"
    end
    on_intel do
      url "$url/$flavour-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$(sha "$flavour-x86_64-unknown-linux-musl.tar.gz")"
    end
  end

  conflicts_with "$conflicts", because: "both install a quack binary"

  def install
    bin.install "bin/quack"
$share  end

  test do
    assert_match version.to_s, shell_output("#{bin}/quack --version")
  end
end
EOF
}

# The binary looks for its bundle in <prefix>/share/quack/defaults.
formula quack Quack quack-plucked \
  "Terminal coding agent for open-weight models" \
  '    (share/"quack").install "share/quack/defaults"
' > "$out/quack.rb"
formula quack-plucked QuackPlucked quack \
  "Terminal coding agent for open-weight models (no hosted model services)" \
  '    (share/"quack").install "share/quack/defaults"
' > "$out/quack-plucked.rb"
echo "wrote $out/quack.rb and $out/quack-plucked.rb"
